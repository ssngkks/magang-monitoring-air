namespace SecurityCerts {

  /**
   * Konfigurasi TLS terverifikasi (blueprint §3.2):
   * - Jika custom CA cert disediakan (server lokal HTTPS self-signed),
   *   verifikasi memakai CA itu (pin).
   * - Jika tidak, verifikasi memakai root CA publik yang relevan
   *   (ISRG Root X1 untuk ngrok/Let's Encrypt). BUKAN setInsecure().
   * - Telegram memakai TELEGRAM_ROOT_CA langsung (DigiCert), bukan via helper ini.
   */
  inline void configureSecureClient(WiFiClientSecure &client, const char *customCa = nullptr) {
    if (customCa != nullptr && strlen(customCa) > 0) {
      client.setCACert(customCa);
    } else {
      client.setCACert(BACKEND_PUBLIC_ROOT_CA);
    }
  }

} // namespace SecurityCerts
